"""Загрузка файлов из панели (``/api/upload``, «Поделиться»): предел тела запроса и строка журнала на каждую загрузку.
Перенесено из верхнего уровня ``webapp.py`` как есть (MONOLITH-PLAN §4 п.7): ``webapp`` реэкспортирует имена,
маршрут ``/api/upload`` — ``routes/sessions.py``.
"""

import os
import re

MAX_BODY = 50 << 20                     # файлы и прочие запросы — до 50 МБ
MAX_VOICE = 300 << 20                   # голосовое на распознавание (?job=1): час записи ≈ 100 МБ (27.11: 102 МБ → 400)
KEEP_CAP = 2 << 30                      # больше предела голосового — всё равно на диск (voice-keep), до 2 ГБ


def upload_log(n: int, secs: float, src: str) -> str:
    """Строка журнала на каждую загрузку (владелец 15.11: «почему так долго загружается фото»): байты, секунды,
    скорость, откуда (telegram — Mini App, browser, focus, bot). Без имени файла и содержимого."""
    line = (f"upload: {n / 1024:.0f} КБ за {secs:.1f} с ({n / 1024 / max(secs, 0.001):.1f} КБ/с) · "
            f"{src or 'неизвестно'}")
    print(line, flush=True)
    return line


# ---------- файл без подписи (владелец 23.11) ----------
# Человек прислал снимок без текста — агент получал «Посмотри файл.» и путь, снимок пропускал и продолжал другую тему.
# Теперь вместо «Посмотри файл.» — пометка: посмотреть, связать с последним вопросом, не уходить в другую тему. В ленте
# чата пометка показывается как прежде — «Посмотри файл.» (``shown``): человек её не писал, и ожидающее сообщение в
# браузере сверяется с журналом по тексту.
FILE_LINE = re.compile(r"^Файл из (?:панели|Telegram): (.+)$", re.M)
DEFAULT = "Посмотри файл."
LOADING = "(файл загружается…)"
IMAGES = frozenset({".jpg", ".jpeg", ".png", ".gif", ".webp", ".heic", ".heif", ".bmp", ".tif", ".tiff", ".avif"})
NOTE = re.compile(r"Человек прислал (?:снимок|снимки|файл|файлы) без подписи\. Посмотри [^\n]*?не ответил на "
                  r"(?:снимок|снимки|файл|файлы)\.")


def note(paths: list[str]) -> str:
    """Пометка для агента: «снимок» — все файлы картинки, иначе «файл»; несколько — множественное число."""
    pic = all(os.path.splitext(p.strip())[1].lower() in IMAGES for p in paths)
    many = len(paths) > 1
    what = ("снимки" if many else "снимок") if pic else ("файлы" if many else "файл")
    it, them = ("их", "ними") if many else ("его", "ним")
    return (f"Человек прислал {what} без подписи. Посмотри {it} и свяжи с последним вопросом. Если неясно — спроси, "
            f"что с {them} сделать. Не продолжай другую тему, пока не ответил на {what}.")


def mark_bare(text: str) -> str:
    """Ввод для агента: файлы без подписи (кроме строк «Файл из …» — пусто или «Посмотри файл.») — пометка вместо
    «Посмотри файл.»; с подписью или без файлов — текст как есть."""
    text = str(text or "")
    paths = FILE_LINE.findall(text)
    if not paths:
        return text
    rest = FILE_LINE.sub("", text).replace(LOADING, "").strip()
    if rest not in ("", DEFAULT):
        return text
    return note(paths) + "\n\n" + "\n".join(m.group(0) for m in FILE_LINE.finditer(text))


def shown(text: str) -> str:
    """Текст для ленты: пометку пульта — обратно в «Посмотри файл.» (человек её не писал)."""
    return NOTE.sub(DEFAULT, text) if "без подписи" in text else text
